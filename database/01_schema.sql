CREATE TABLE IF NOT EXISTS Department (
 dept_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dept_name VARCHAR(100) NOT NULL UNIQUE, location VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS Employee (
 emp_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dept_id INTEGER NOT NULL REFERENCES Department(dept_id),
 name VARCHAR(120) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
 phone VARCHAR(20), dob DATE, designation VARCHAR(100),
 join_date DATE NOT NULL DEFAULT CURRENT_DATE,
 employment_status VARCHAR(20) NOT NULL DEFAULT 'Active'
 CHECK (employment_status IN ('Active','Inactive','On Leave','Resigned'))
);
CREATE TABLE IF NOT EXISTS Attendance (
 att_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 emp_id INTEGER NOT NULL REFERENCES Employee(emp_id) ON DELETE CASCADE,
 attendance_date DATE NOT NULL, check_in TIME, check_out TIME,
 status VARCHAR(20) NOT NULL CHECK(status IN ('Present','Absent','Late','Leave')),
 UNIQUE(emp_id,attendance_date),
 CHECK(check_out IS NULL OR check_in IS NOT NULL),
 CHECK(check_in IS NULL OR check_out IS NULL OR check_out >= check_in)
);
CREATE TABLE IF NOT EXISTS LeaveRecord (
 leave_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 emp_id INTEGER NOT NULL REFERENCES Employee(emp_id) ON DELETE CASCADE,
 leave_type VARCHAR(50) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'Pending'
 CHECK(status IN ('Pending','Approved','Rejected')),
 reason TEXT, CHECK(end_date >= start_date)
);
CREATE TABLE IF NOT EXISTS Salary (
 salary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 emp_id INTEGER NOT NULL REFERENCES Employee(emp_id) ON DELETE CASCADE,
 salary_month SMALLINT NOT NULL CHECK(salary_month BETWEEN 1 AND 12),
 salary_year SMALLINT NOT NULL CHECK(salary_year BETWEEN 2000 AND 2100),
 basic_salary NUMERIC(12,2) NOT NULL CHECK(basic_salary >= 0),
 allowances NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(allowances >= 0),
 deductions NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(deductions >= 0),
 UNIQUE(emp_id,salary_month,salary_year)
);
CREATE TABLE IF NOT EXISTS Payroll (
 payroll_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 emp_id INTEGER NOT NULL REFERENCES Employee(emp_id) ON DELETE CASCADE,
 salary_month SMALLINT NOT NULL CHECK(salary_month BETWEEN 1 AND 12),
 salary_year SMALLINT NOT NULL CHECK(salary_year BETWEEN 2000 AND 2100),
 gross_salary NUMERIC(12,2) NOT NULL, tax_amount NUMERIC(12,2) NOT NULL,
 total_deductions NUMERIC(12,2) NOT NULL, net_salary NUMERIC(12,2) NOT NULL,
 generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(emp_id,salary_month,salary_year)
);
CREATE TABLE IF NOT EXISTS app_users (
 user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role VARCHAR(30) NOT NULL CHECK(role IN ('admin','hr_manager','accountant','employee_user')),
 emp_id INTEGER UNIQUE REFERENCES Employee(emp_id) ON DELETE SET NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK((role='employee_user' AND emp_id IS NOT NULL) OR role<>'employee_user')
);
